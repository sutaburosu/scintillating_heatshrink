def parse_header_file(filepath):
    """Parse a C header file and extract sprite metadata and compressed data."""
    with open(filepath, 'r') as f:
        content = f.read()

    result = {
        'filename': os.path.basename(filepath),
        'path': filepath,
        'comments': [],
        'datasize': 0,
        'frames': 0,
        'duration': 100,
        'flags': 0,
        'palette_entries': 0,
        'compressed_data': b''
    }

    # Extract comments
    comment_pattern = r'^//(.+)$'
    for line in content.split('\n'):
        match = re.match(comment_pattern, line.strip())
        if match:
            result['comments'].append(match.group(1).strip())

    # Extract struct fields
    datasize_match = re.search(r'uint16_t datasize\s*=\s*(\d+);', content)
    if datasize_match:
        result['datasize'] = int(datasize_match.group(1))

    frames_match = re.search(r'uint16_t frames\s*=\s*(\d+);', content)
    if frames_match:
        result['frames'] = int(frames_match.group(1))

    duration_match = re.search(r'uint16_t duration\s*=\s*(\d+);', content)
    if duration_match:
        result['duration'] = int(duration_match.group(1))

    flags_match = re.search(r'uint8_t flags\s*=\s*(\d+);', content)
    if flags_match:
        result['flags'] = int(flags_match.group(1))

    palette_match = re.search(r'uint8_t palette_entries\s*=\s*(\d+);', content)
    if palette_match:
        result['palette_entries'] = int(palette_match.group(1))

    # Extract compressed data bytes
    hs_data_match = re.search(
        r'uint8_t\s+hs_data\[\d+\]\s*=\s*\{([^}]+)\}',
        content,
        re.DOTALL
    )
    if hs_data_match:
        hex_str = hs_data_match.group(1)
        hex_bytes = re.findall(r'0x([0-9a-fA-F]{2})', hex_str)
        result['compressed_data'] = bytes(int(b, 16) for b in hex_bytes)

    return result


def decompress_sprite(header_data):
    """Decompress sprite data and return palette + frames."""
    compressed = header_data['compressed_data']
    if not compressed:
        return None, []

    try:
        decompressed = decompress(compressed, 8, 7)
    except Exception as e:
        print(f'[decompress_sprite] Failed to decompress {header_data["filename"]}: {e}')
        return None, []

    # First bytes are palette (RGB triplets)
    palette_entries = header_data['palette_entries']
    palette_size = palette_entries * 3

    if len(decompressed) < palette_size:
        return None, []

    palette = []
    for i in range(palette_entries):
        r = decompressed[i * 3]
        g = decompressed[i * 3 + 1]
        b = decompressed[i * 3 + 2]
        palette.append((r, g, b))

    # Remaining bytes are pixel data (one byte per pixel per frame)
    pixel_data = decompressed[palette_size:]
    pixels_per_frame = 16 * 16  # 256 pixels for 16x16

    frames = []
    for frame_idx in range(header_data['frames']):
        start = frame_idx * pixels_per_frame
        end = start + pixels_per_frame
        if end <= len(pixel_data):
            frames.append(pixel_data[start:end])

    return palette, frames


def pixels_to_image(pixels, palette, size, transform_mode):
    """Convert pixel indices and palette to a QPixmap with specified scaling.
    
    Transparent pixels (palette index 0) are rendered as fully transparent,
    allowing the cross-hatch background to show through.
    """
    img = QImage(16, 16, QImage.Format.Format_ARGB32)

    # Fill with transparent background
    img.fill(Qt.GlobalColor.transparent)

    # Draw pixels
    for y in range(16):
        for x in range(16):
            idx = y * 16 + x
            if idx >= len(pixels):
                continue
            
            pixel_idx = pixels[idx]
            
            if pixel_idx != 0:
                # Solid pixel - use palette color
                r, g, b = palette[pixel_idx]
                img.setPixel(x, y, QColor(r, g, b).rgb())

    # Scale up with specified transform mode
    scaled = img.scaled(
        size, size,
        Qt.AspectRatioMode.KeepAspectRatio,
        transform_mode
    )

    return QPixmap.fromImage(scaled)


# Mapping from string to Qt transform mode
TRANSFORM_MODES = {
    'Nearest Neighbor': Qt.TransformationMode.FastTransformation,
    'Bicubic': Qt.TransformationMode.SmoothTransformation,
}


class BackgroundWidget(QWidget):
    """Animated grid of squares rotated 45 degrees on black background.
    
    Grey lines on black background, slowly panning in x and y.
    """
    
    def __init__(self, parent=None):
        super().__init__(parent)
        self.setAttribute(Qt.WidgetAttribute.WA_TransparentForMouseEvents)
        self.setAttribute(Qt.WidgetAttribute.WA_NoSystemBackground)
        self.offset_x = 0.0
        self.offset_y = 0.0
        self.timer = QTimer(self)
        self.timer.timeout.connect(self.animate)
        self.timer.start(33)  # ~30 fps for smooth animation
        
    def animate(self):
        self.offset_x += 0.5
        self.offset_y += 0.5
        # Wrap at pattern period to avoid floating point issues
        # Pattern repeats when offset changes by step (perpendicular spacing)
        period = 16 * 16  # full cycle before floating point drift
        if self.offset_x >= period:
            self.offset_x -= period
        if self.offset_y >= period:
            self.offset_y -= period
        self.update()
        
    def resizeEvent(self, event):
        super().resizeEvent(event)
        self.update()
        
    def paintEvent(self, event):
        painter = QPainter(self)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
        
        # Black background
        painter.fillRect(self.rect(), QColor(0, 0, 0))
        
        # Grid of squares rotated 45 degrees
        # Lines at 45°: x - y = c
        # Lines at 135°: x + y = c
        # Perpendicular spacing between parallel lines = 16px
        # So c values are spaced by 16 * sqrt(2)
        import math
        step = 16 * math.sqrt(2)
        
        # Darker grey, wider pen
        pen = QPen(QColor(80, 80, 80), 1.75)
        painter.setPen(pen)
        
        w = self.width()
        h = self.height()
        
        # Calculate the effective c offset for each line family
        c45_offset = self.offset_x - self.offset_y
        c135_offset = self.offset_x + self.offset_y
        
        # Range of c values to cover the widget with generous margin
        # Need extra margin to ensure lines at edges are drawn
        diag = math.sqrt(w * w + h * h)
        margin = diag / step + 2
        
        min_c = -diag / step - margin
        max_c = diag / step + margin
        
        # Draw 45° lines: x - y = c_int * step + c45_offset
        c_start = math.floor(min_c)
        c_end = math.ceil(max_c)
        
        for c_int in range(c_start, c_end + 1):
            c = c_int * step + c45_offset
            
            # Find intersections with widget bounds [0,w] x [0,h]
            # For 45° lines (direction (1,1)), order by increasing x+y
            candidates = []
            # Top edge: y=0, x=c
            if 0 <= c <= w:
                candidates.append((c, 0.0))
            # Bottom edge: y=h, x=c+h
            if 0 <= c + h <= w:
                candidates.append((c + h, float(h)))
            # Left edge: x=0, y=-c
            if 0 <= -c <= h:
                candidates.append((0.0, -c))
            # Right edge: x=w, y=w-c
            if 0 <= w - c <= h:
                candidates.append((float(w), w - c))
            
            if len(candidates) >= 2:
                # Sort by x coordinate (for 45° lines, x increases along the line)
                candidates.sort(key=lambda p: p[0])
                painter.drawLine(
                    int(round(candidates[0][0])), int(round(candidates[0][1])),
                    int(round(candidates[-1][0])), int(round(candidates[-1][1])))
        
        # Draw 135° lines: x + y = c_int * step + c135_offset
        for c_int in range(c_start, c_end + 1):
            c = c_int * step + c135_offset
            
            # Find intersections with widget bounds [0,w] x [0,h]
            # For 135° lines (direction (-1,1)), order by increasing x
            candidates = []
            # Top edge: y=0, x=c
            if 0 <= c <= w:
                candidates.append((c, 0.0))
            # Bottom edge: y=h, x=c-h
            if 0 <= c - h <= w:
                candidates.append((c - h, float(h)))
            # Left edge: x=0, y=c
            if 0 <= c <= h:
                candidates.append((0.0, c))
            # Right edge: x=w, y=c-w
            if 0 <= c - w <= h:
                candidates.append((float(w), c - w))
            
            if len(candidates) >= 2:
                # Sort by x coordinate (for 135° lines, x decreases along the line)
                candidates.sort(key=lambda p: p[0])
                painter.drawLine(
                    int(round(candidates[0][0])), int(round(candidates[0][1])),
                    int(round(candidates[-1][0])), int(round(candidates[-1][1])))
        
        painter.end()


class SpriteViewer(QMainWindow):
    """Main window for viewing heatshrink-compressed sprite animations."""

    def __init__(self, header_files=None):
        super().__init__()
        self.sprites = []
        self.current_sprite_idx = 0
        self.current_frame = 0
        self.playing = True  # Auto-play by default
        self.magnification = 24
        self.fps = 10
        self.transform_mode = Qt.TransformationMode.FastTransformation  # Matches default combo selection
        self.timer = QTimer(self)
        self.timer.timeout.connect(self.next_frame)
        # Cached decompressed data (avoids re-decompressing on every frame/scale change)
        self._cached_palette = None
        self._cached_frames = None

        self.init_ui()

        # Load sprites
        if header_files:
            files = header_files
        else:
            files = sorted(glob.glob('GIF/*.h'))

        for f in files:
            if os.path.exists(f):
                header = parse_header_file(f)
                if header['compressed_data']:
                    self.sprites.append(header)

        if self.sprites:
            self.load_sprite(0)
            # Start auto-play
            self.playing = True
            self.play_btn.setText('Pause')
            self.timer.start(int(1000 / self.fps))
        else:
            self.statusBar().showMessage('No sprite headers found. Add GIF/*.h files.')
        
        # Size window to fit max zoom (30x) with visible background border
        # At 30x: panels = 480px each, gap = 240px, total content = 1200px wide
        # Add ~100px border on each side for visible background
        self.resize(1320, 890)

