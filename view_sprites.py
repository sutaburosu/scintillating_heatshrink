    def load_sprite(self, idx):
        """Load a sprite and its source GIF."""
        if idx < 0 or idx >= len(self.sprites):
            return

        self.current_sprite_idx = idx
        sprite = self.sprites[idx]
        
        # Update sprite combo box (block signals to avoid recursion)
        self.sprite_combo.blockSignals(True)
        self.sprite_combo.clear()
        for i, s in enumerate(self.sprites):
            self.sprite_combo.addItem(os.path.basename(s['path']).replace('.h', ''))
        self.sprite_combo.setCurrentIndex(idx)
        self.sprite_combo.blockSignals(False)
        
        self.current_frame = 0
        self.frame_slider.setMaximum(max(0, sprite['frames'] - 1))

        # Decompress and cache
        palette, frames = decompress_sprite(sprite)

        if palette and frames:
            self._cached_palette = palette
            self._cached_frames = frames

            # Display reconstructed frame with current magnification and scaling
            pixmap = pixels_to_image(frames[0], palette, 16 * self.magnification, self.transform_mode)
            self.reconstructed_label.setPixmap(pixmap)
            self.reconstructed_label.setText('')

            # Display source GIF if it exists
            gif_path = sprite['path'].replace('.h', '.gif')
            if os.path.exists(gif_path):
                self._show_gif(gif_path)
            else:
                self.source_label.setText('No source GIF found')
                self.source_label.setPixmap(QPixmap())

            self.status_bar.showMessage(
                f'{sprite["filename"]} | {sprite["frames"]} frames | '
                f'{sprite["datasize"]} bytes compressed | {len(palette)} colors'
            )
        else:
            self._cached_palette = None
            self._cached_frames = None
            self.reconstructed_label.setText('Failed to decompress')
            self.source_label.setText('')
            self.source_label.setPixmap(QPixmap())
            self.status_bar.showMessage('Decompression failed')

    def _show_gif(self, gif_path):
        """Display a GIF frame with same magnification as reconstructed."""
        try:
            gif = Image.open(gif_path)
            gif.seek(self.current_frame)
            # Convert to RGBA to preserve transparency
            if gif.mode not in ('RGBA',):
                rgba = gif.convert('RGBA')
            else:
                rgba = gif

            # Scale to match reconstructed size (16 * magnification)
            target_size = 16 * self.magnification
            width, height = rgba.size
            scale = target_size / max(width, height)
            new_size = (int(width * scale), int(height * scale))
            
            # Use appropriate resampling based on transform mode
            if self.transform_mode == Qt.TransformationMode.FastTransformation:
                resample = Image.Resampling.NEAREST
            else:
                resample = Image.Resampling.BICUBIC
            
            rgba = rgba.resize(new_size, resample)

            # Convert to QPixmap with alpha channel
            # Format_RGBA8888 stores bytes as R,G,B,A matching PIL's tobytes() output
            data = rgba.tobytes()
            qimg = QImage(data, rgba.width, rgba.height, QImage.Format.Format_RGBA8888)
            pixmap = QPixmap.fromImage(qimg)
            self.source_label.setPixmap(pixmap)
            self.source_label.setText('')
        except Exception as e:
            self.source_label.setText(f'Error loading GIF: {e}')
            self.source_label.setPixmap(QPixmap())

    def sprite_changed(self, idx):
        """Handle sprite selection change."""
        if self.playing:
            self.toggle_play()
        self.load_sprite(idx)
        # Restart playback
        self.playing = True
        self.play_btn.setText('Pause')
        self.timer.start(int(1000 / self.fps))

    def toggle_play(self):
        """Toggle playback."""
        self.playing = not self.playing
        if self.playing:
            self.play_btn.setText('Pause')
            self.fps = self.fps_spin.value()
            self.timer.start(int(1000 / self.fps))
        else:
            self.play_btn.setText('Play')
            self.timer.stop()

    def next_frame(self):
        """Advance to next frame."""
        sprite = self.sprites[self.current_sprite_idx]
        self.current_frame = (self.current_frame + 1) % sprite['frames']
        self.frame_slider.setValue(self.current_frame)
        self.show_current_frame()

    def prev_frame(self):
        """Go to previous frame."""
        sprite = self.sprites[self.current_sprite_idx]
        self.current_frame = (self.current_frame - 1) % sprite['frames']
        self.frame_slider.setValue(self.current_frame)
        self.show_current_frame()

    def next_sprite(self):
        """Go to next sprite/animation."""
        if len(self.sprites) <= 1:
            return
        new_idx = (self.current_sprite_idx + 1) % len(self.sprites)
        self.sprite_combo.setCurrentIndex(new_idx)

    def prev_sprite(self):
        """Go to previous sprite/animation."""
        if len(self.sprites) <= 1:
            return
        new_idx = (self.current_sprite_idx - 1) % len(self.sprites)
        self.sprite_combo.setCurrentIndex(new_idx)

    def jump_to_frame(self, frame_idx):
        """Jump to a specific frame."""
        self.current_frame = frame_idx
        self.show_current_frame()

    def show_current_frame(self):
        """Display the current frame."""
        palette = self._cached_palette
        frames = self._cached_frames

        if palette and frames and self.current_frame < len(frames):
            pixmap = pixels_to_image(
                frames[self.current_frame], 
                palette, 
                16 * self.magnification, 
                self.transform_mode
            )
            self.reconstructed_label.setPixmap(pixmap)
            self.reconstructed_label.setText('')

        # Update source GIF frame
        sprite = self.sprites[self.current_sprite_idx]
        gif_path = sprite['path'].replace('.h', '.gif')
        if os.path.exists(gif_path):
            self._show_gif(gif_path)

    def fps_changed(self, fps):
        """Handle FPS change."""
        if self.playing:
            self.timer.start(int(1000 / fps))

    def mag_changed(self, mag):
        """Handle magnification change."""
        self.magnification = mag
        self.mag_label.setText(f'{mag}x')
        # Update gap to maintain half-GIF-width spacing
        self._display_container.layout().setSpacing(8 * self.magnification)
        # Refresh current display
        if self.sprites:
            self.show_current_frame()

    def _zoom_in(self):
        """Zoom in by 1."""
        self.mag_slider.setValue(min(30, self.magnification + 1))

    def _zoom_out(self):
        """Zoom out by 1."""
        self.mag_slider.setValue(max(2, self.magnification - 1))

    def scale_changed(self, mode_name):
        """Handle scaling mode change."""
        self.transform_mode = TRANSFORM_MODES[mode_name]
        # Refresh current display
        if self.sprites:
            self.show_current_frame()

    def keyPressEvent(self, event):
        """Handle keyboard shortcuts."""
        modifiers = event.modifiers()
        
        # Ctrl+Left/Right for frame navigation (QShortcut doesn't handle modifiers cleanly)
        if event.key() == Qt.Key.Key_Left and modifiers & Qt.KeyboardModifier.ControlModifier:
            self.prev_frame()
        elif event.key() == Qt.Key.Key_Right and modifiers & Qt.KeyboardModifier.ControlModifier:
            self.next_frame()
        else:
            super().keyPressEvent(event)

    def wheelEvent(self, event):
        """Handle mouse wheel for zoom."""
        if event.angleDelta().y() > 0:
            self.mag_slider.setValue(min(30, self.magnification + 1))
        else:
            self.mag_slider.setValue(max(2, self.magnification - 1))

    def eventFilter(self, obj, event):
        """Event filter to size background when display_container is shown."""
        if obj is getattr(self, '_display_container', None):
            if event.type() == QEvent.Type.Show:
                parent = cast(QWidgetType, self.background.parent())
                if parent:
                    self.background.setGeometry(parent.rect())
                    self.background.update()
        return super().eventFilter(obj, event)

    def resizeEvent(self, event):
        """Handle window resize to keep background in sync."""
        super().resizeEvent(event)
        if hasattr(self, 'background'):
            parent = cast(QWidgetType, self.background.parent())
            if parent:
                self.background.setGeometry(parent.rect())
                self.background.update()


